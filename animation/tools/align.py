"""Find when each sentence (and word) of the narrator sections is spoken, using faster-whisper word
timestamps matched against the script text. Writes timing.js for the scenes.

Needs: pip install faster-whisper
Usage: python3 animation/tools/align.py scripts/ep01-cannae/voice/narrator animation/episodes/ep01/timing.js
"""
import difflib, json, re, subprocess, sys, pathlib
import numpy as np
from faster_whisper import WhisperModel

src, dst = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
timings = json.loads((src / "timings.json").read_text())
model = WhisperModel("base.en", device="cpu", compute_type="int8")
norm = lambda w: re.sub(r"[^a-z0-9]", "", w.lower())

def heard(mp3):
    pcm = subprocess.run(["ffmpeg", "-v", "error", "-i", str(mp3), "-f", "f32le", "-ac", "1", "-ar", "16000", "-"],
                         capture_output=True, check=True).stdout
    segs, _ = model.transcribe(np.frombuffer(pcm, np.float32), word_timestamps=True)
    # split hyphenated/compound recognitions ("eye patch") into tokens sharing a start time
    return [(norm(p), w.start) for s in segs for w in s.words for p in w.word.split() if norm(p)]

out = {}
for sec in timings:
    text = (src / sec["file"].replace(".mp3", ".txt")).read_text().replace("\n", " ")
    sents = [s.strip() for s in re.split(r"(?<=[.?!])['\"]?\s+", text) if s.strip()]
    script = [(norm(w), i) for i, s in enumerate(sents) for w in s.replace("—", " ").replace("-", " ").split() if norm(w)]
    rec = heard(src / sec["file"])
    sm = difflib.SequenceMatcher(None, [w for w, _ in script], [w for w, _ in rec], autojunk=False)
    times = [None] * len(script)
    for a, b, n in sm.get_matching_blocks():
        for k in range(n):
            times[a + k] = rec[b + k][1]
    # fill unmatched words by interpolating between matched neighbours
    known = [i for i, t in enumerate(times) if t is not None]
    for i in range(len(times)):
        if times[i] is None:
            lo = max([k for k in known if k < i], default=None)
            hi = min([k for k in known if k > i], default=None)
            if lo is None: times[i] = times[hi]
            elif hi is None: times[i] = times[lo]
            else: times[i] = times[lo] + (times[hi] - times[lo]) * (i - lo) / (hi - lo)
    starts = [round(next(t for t, (_, si) in zip(times, script) if si == i), 2) for i in range(len(sents))]
    words = [[w, round(t, 2)] for (w, _), t in zip(script, times)]
    out[sec["index"]] = {"duration": round(sec["duration"], 2), "s": starts, "text": sents, "w": words}
    print(sec["index"], f"{sec['duration']:6.1f}s", f"matched {len(known)}/{len(script)} words")
    for s0, tx in zip(starts, sents):
        print(f"   {s0:6.2f}  {tx[:70]}")

dst.write_text("// Generated by tools/align.py: sentence (s) and word (w) start times in seconds within each narrator section.\n"
               f"globalThis.TIMING = {json.dumps(out)};\n"
               "if (typeof module !== 'undefined') module.exports = globalThis.TIMING;\n")
